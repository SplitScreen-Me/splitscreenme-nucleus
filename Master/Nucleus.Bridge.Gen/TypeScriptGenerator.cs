using System;
using System.Linq;
using System.Reflection;
using System.Text.RegularExpressions;
using Newtonsoft.Json.Serialization;
using Nucleus.Bridge.Model;

namespace Nucleus.Bridge.Gen;

/// <summary>
/// Generates the TypeScript side of a contract: DTO interfaces and enum unions with their docs, the method and event
/// maps the runtime is typed with, the handler shape a mock implements, and the protocol constants.
/// The output depends only on the model, so it is deterministic. It uses erasable syntax only (no <c>enum</c>, no
/// <c>namespace</c>), so Node can run it with type stripping.
/// </summary>
public static class TypeScriptGenerator
{
    private static readonly Regex Identifier = new("^[A-Za-z_$][A-Za-z0-9_$]*$");
    private static readonly CamelCaseNamingStrategy Naming = new();

    /// <summary>Generates <c>contract.ts</c> for <paramref name="model"/>.</summary>
    public static string Generate(ContractModel model)
    {
        var ts = new TsWriter();
        ts.Line("// <auto-generated>")
            .Line("// Generated by Nucleus.Bridge.Gen from the C# contract (Master/Nucleus.Bridge/Contracts).")
            .Line("// Do not edit: change the contract, then run `npm run bridge:gen`. See docs/webui/bridge-howto.md.")
            .Line("// </auto-generated>");
        WriteProtocol(ts, model);
        WriteEnums(ts, model);
        WriteTypes(ts, model);
        WriteMethods(ts, model);
        WriteEvents(ts, model);
        return ts.ToString();
    }

    private static void WriteProtocol(TsWriter ts, ContractModel model)
    {
        Section(ts, "Protocol");
        ts.Doc("Version of the wire protocol. `app.hello` returns the host's: the UI refuses to run when they differ.")
            .Line($"export const protocolVersion = {BridgeHost.ProtocolVersion};")
            .Gap()
            .Doc("Hash of the contract this file was generated from. `app.hello` returns the host's: the UI refuses to run when they differ.")
            .Line($"export const contractHash = '{model.Hash}';")
            .Gap()
            .Doc("JSON-RPC error code of each kind of error the host returns.")
            .Block("export const bridgeErrorCodes = {", () =>
            {
                foreach (var field in typeof(BridgeErrorKind).GetFields(BindingFlags.Public | BindingFlags.Static).OrderBy(f => f.MetadataToken))
                {
                    ts.Line($"{CamelCase(field.Name)}: {(int)field.GetValue(null)},");
                }
            }, "} as const;")
            .Gap()
            .Doc("Kind of an error returned by the host.")
            .Line("export type BridgeErrorKind = keyof typeof bridgeErrorCodes;")
            .Gap()
            .Doc("A date and time in ISO 8601 format (UTC for C# `DateTime`), for example `2026-10-11T14:30:00Z`.")
            .Line("export type IsoDateString = string;")
            .Gap()
            .Doc("A value, or a promise of it.")
            .Line("export type Awaitable<T> = T | PromiseLike<T>;");
    }

    private static void WriteEnums(TsWriter ts, ContractModel model)
    {
        Section(ts, "Enums");
        foreach (var type in model.Types.OfType<EnumTypeModel>())
        {
            var literals = type.Members.Select(m => Quote(m.Value)).ToList();
            var union = string.Join(" | ", literals);
            ts.Doc(type.Doc);
            if (ts.Fits($"export type {type.Name} = {union};".Length))
            {
                ts.Line($"export type {type.Name} = {union};");
            }
            else
            {
                ts.Block($"export type {type.Name} =", () => literals.ForEach(l => ts.Line("| " + l)), ";");
            }

            ts.Gap()
                .Doc($"Every {{@link {type.Name}}}, in declaration order.")
                .Block($"export const {CamelCase(type.Name)}Values = [", () =>
                {
                    foreach (var member in type.Members)
                    {
                        ts.Doc(member.Doc).Line(Quote(member.Value) + ",");
                    }
                }, $"] as const satisfies readonly {type.Name}[];")
                .Gap();
        }
    }

    private static void WriteTypes(TsWriter ts, ContractModel model)
    {
        Section(ts, "Types");
        foreach (var type in model.Types.OfType<ObjectTypeModel>())
        {
            ts.Doc(type.Doc).Block($"export interface {type.Name} {{", () =>
            {
                foreach (var property in type.Properties)
                {
                    var optional = property.Type.Nullable ? "?" : "";
                    ts.Doc(property.Doc).Line($"{Key(property.Name)}{optional}: {TypeOf(property.Type.NonNullable())};");
                }
            }, "}").Gap();
        }
    }

    private static void WriteMethods(TsWriter ts, ContractModel model)
    {
        Section(ts, "Methods");
        ts.Doc("Every method, by wire name: its `params` (`void` when it takes none) and its `result` (`void` when it returns nothing).")
            .Block("export interface BridgeMethods {", () =>
            {
                foreach (var method in model.Methods)
                {
                    ts.Doc(method.Doc).Line($"{Quote(method.WireName)}: {{ params: {ParamsOf(method)}; result: {ResultOf(method)} }};");
                }
            }, "}")
            .Gap()
            .Doc("What an in-process implementation of the contract provides (the mock does): one function per method, by service.")
            .Block("export interface BridgeHandlers {", () =>
            {
                foreach (var service in model.Services)
                {
                    ts.Doc(service.Doc).Block($"{Key(service.Name)}: {{", () =>
                    {
                        foreach (var method in service.Methods)
                        {
                            var parameters = method.Params == null ? "" : $"params: {ParamsOf(method)}";
                            ts.Doc(method.Doc).Line($"{Key(method.Name)}: ({parameters}) => Awaitable<{ResultOf(method)}>;");
                        }
                    }, "};");
                }
            }, "}")
            .Gap()
            .Doc("Every service and its methods, with whether each method takes params. The typed proxy (`bridge.library.list()`) is built from it.")
            .Block("export const bridgeServices = {", () =>
            {
                foreach (var service in model.Services)
                {
                    ts.Block($"{Key(service.Name)}: {{", () =>
                    {
                        foreach (var method in service.Methods)
                        {
                            ts.Line($"{Key(method.Name)}: {{ params: {(method.Params == null ? "false" : "true")} }},");
                        }
                    }, "},");
                }
            }, "} as const;");
    }

    private static void WriteEvents(TsWriter ts, ContractModel model)
    {
        Section(ts, "Events");
        ts.Doc("Every event, by name, with its payload.")
            .Block("export interface BridgeEvents {", () =>
            {
                foreach (var evt in model.Events)
                {
                    ts.Doc(evt.Doc).Line($"{Quote(evt.Name)}: {evt.PayloadName};");
                }
            }, "}")
            .Gap()
            .Doc("Methods each event makes stale: the client refetches their queries when the event arrives.")
            .Block("export const eventInvalidations: { readonly [E in keyof BridgeEvents]: readonly (keyof BridgeMethods)[] } = {", () =>
            {
                foreach (var evt in model.Events)
                {
                    ts.Line($"{Quote(evt.Name)}: [{string.Join(", ", evt.Invalidates.Select(Quote))}],");
                }
            }, "};");
    }

    private static string ParamsOf(MethodModel method) => method.Params == null ? "void" : TypeOf(method.Params);

    private static string ResultOf(MethodModel method) => method.Result == null ? "void" : TypeOf(method.Result);

    private static string TypeOf(TypeRef type)
    {
        var core = type.Kind switch
        {
            TypeRefKind.String => "string",
            TypeRefKind.Number => "number",
            TypeRefKind.Boolean => "boolean",
            TypeRefKind.DateTime => "IsoDateString",
            TypeRefKind.Array => ArrayOf(type.Item!),
            TypeRefKind.Map => $"Record<string, {TypeOf(type.Item!)}>",
            TypeRefKind.Named => type.Name!,
            _ => throw new ArgumentOutOfRangeException(nameof(type), type.Kind, null),
        };
        return type.Nullable ? core + " | null" : core;
    }

    private static string ArrayOf(TypeRef item)
    {
        var element = TypeOf(item);
        return item.Nullable ? $"({element})[]" : element + "[]";
    }

    private static void Section(TsWriter ts, string title) =>
        ts.Gap().Line($"// {title} {new string('-', 100 - title.Length)}").Gap();

    private static string Key(string name) => Identifier.IsMatch(name) ? name : Quote(name);

    private static string Quote(string value) => "'" + value.Replace("\\", "\\\\").Replace("'", "\\'") + "'";

    private static string CamelCase(string name) => Naming.GetPropertyName(name, false);
}
